//! Combined mode: Grok OS sandbox + DevCage-ready environment.
//!
//! `devcage grok` launches the host Grok CLI with a sandbox profile and
//! session data defaults that cooperate with nested `devcage run`.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode, Stdio};

use crate::config::{data_dir_for_grok_sandbox_child, resolve_workspace, Config};
use crate::util::which;

/// Embedded permission recipe (same as `examples/grok/config.toml`).
const EMBEDDED_CONFIG_TOML: &str = include_str!("../examples/grok/config.toml");

/// Ambient secrets / agent sockets removed from the Grok child environment.
const SCRUB_ENV: &[&str] = &[
    "SSH_AUTH_SOCK",
    "SSH_AGENT_PID",
    "AWS_SECRET_ACCESS_KEY",
    "AWS_ACCESS_KEY_ID",
    "AWS_SESSION_TOKEN",
    "AWS_SECURITY_TOKEN",
    "GITHUB_TOKEN",
    "GH_TOKEN",
    "OPENAI_API_KEY",
    "ANTHROPIC_API_KEY",
    // Keep XAI / Grok usable; do not scrub XAI_API_KEY.
];

/// Parameters for [`run_grok_mode`].
#[derive(Debug, Clone)]
#[allow(clippy::struct_excessive_bools)]
pub struct GrokModeParams {
    /// Grok `--sandbox` profile name (e.g. `keys-first`, `workspace`).
    pub sandbox: String,
    /// Do not create/update `.grok/` recipes.
    pub no_init: bool,
    /// Overwrite existing recipe files when seeding.
    pub force_init: bool,
    /// Allow nested `devcage run -p host` (sets `DEVCAGE_DENY_HOST=0`).
    pub allow_host_profile: bool,
    /// Print command/env only; do not exec Grok.
    pub print_only: bool,
    /// Project workspace (default: cwd / git root).
    pub workspace: Option<PathBuf>,
    /// Extra args forwarded to `grok` after `--sandbox <profile>`.
    pub args: Vec<String>,
}

/// Seed project `.grok/` sandbox + permission recipes from embedded templates.
///
/// Generated `sandbox.toml` files are refreshed when they are missing a known
/// fix (Linux Docker + exact `.env` deny). Hand-written recipes are left alone.
///
/// # Errors
///
/// Returns an error if directories or files cannot be written.
pub fn init_grok_recipes(workspace: &Path, force: bool) -> anyhow::Result<Vec<String>> {
    let grok_dir = workspace.join(".grok");
    fs::create_dir_all(&grok_dir)?;
    let mut written = Vec::new();

    let sandbox_path = grok_dir.join("sandbox.toml");
    let refresh_sandbox = force
        || !sandbox_path.exists()
        || fs::read_to_string(&sandbox_path)
            .ok()
            .is_some_and(|existing| generated_sandbox_recipe_stale(&existing));
    if refresh_sandbox {
        fs::write(&sandbox_path, render_sandbox_toml())?;
        written.push(".grok/sandbox.toml".to_owned());
    }

    let config_path = grok_dir.join("config.toml");
    if force || !config_path.exists() {
        fs::write(&config_path, EMBEDDED_CONFIG_TOML)?;
        written.push(".grok/config.toml".to_owned());
    }
    Ok(written)
}

/// True when `body` is a DevCage-generated recipe that predates Linux Docker / exact deny.
fn generated_sandbox_recipe_stale(body: &str) -> bool {
    if !body.contains("Generated by devcage init-grok") {
        return false;
    }
    body.contains("restrict_network = true") || !body.contains("\n  \".env\",")
}

fn warn_if_custom_recipe_blocks_docker(workspace: &Path) {
    let path = workspace.join(".grok/sandbox.toml");
    let Ok(body) = fs::read_to_string(path) else {
        return;
    };
    if body.contains("restrict_network = true") {
        eprintln!(
            "devcage: warning: .grok/sandbox.toml has restrict_network=true; \
             nested Docker on Linux cannot reach docker.sock. \
             Re-seed generated recipes: devcage init-grok --force"
        );
    }
}

/// Build `keys-first` sandbox.toml with absolute tool paths for this host.
///
/// Grok `strict` only allows CWD + system paths; without Homebrew / Colima /
/// `~/.local/bin`, nested `devcage` + Docker fail with Operation not permitted.
///
/// **Only directories** may appear in `read_only` / `read_write` — Grok refuses to
/// start if a listed path is a file (e.g. `~/.gitconfig`).
fn render_sandbox_toml() -> String {
    let mut read_only: Vec<String> = Vec::new();
    for p in ["/opt/homebrew", "/usr/local"] {
        push_dir_if_present(&mut read_only, Path::new(p));
    }
    if let Some(home) = std::env::var_os("HOME") {
        let h = PathBuf::from(home);
        for rel in [
            ".local/bin",
            ".grok/bin",
            ".colima",
            // Docker CLI may consult this dir; deny still blocks config.json secrets.
            ".docker",
            // Developer tooling (directories only — not files like .gitconfig).
            ".cargo/bin",
            ".rustup",
            // Parent of ~/.gitconfig so git can read config if needed.
            // (Listing the home dir is broader; prefer only if tools require it.)
        ] {
            push_dir_if_present(&mut read_only, &h.join(rel));
        }
    }
    // Always include standard prefixes even if missing (create-not-required; Grok
    // validates type when the path exists).
    if read_only.is_empty() {
        read_only.push("/opt/homebrew".to_owned());
        read_only.push("/usr/local".to_owned());
    }
    let ro = read_only
        .iter()
        .map(|p| format!("  \"{}\",", escape_toml_string(p)))
        .collect::<Vec<_>>()
        .join("\n");

    format!(
        r#"# Generated by devcage init-grok / devcage grok — keys-first profile.
# Extends Grok `strict` (project-focused reads) + tool directories for nested DevCage.
# Re-seed after upgrades: devcage init-grok --force
#
# restrict_network is OFF. On Linux, Grok implements it with seccomp that also
# blocks connect() to the Docker unix socket, so nested `devcage run` fails.
# Hard no-network remains `devcage run -p offline|untrusted`.
# On macOS, restrict_network is a no-op either way.
#
# deny: exact `.env` / `local.env` / `.env.local` so Linux bind-over covers
# files created after start. Globs remain for macOS + existing nested files.
#
# IMPORTANT: read_only/read_write entries must be directories, not files.

[profiles.keys-first]
extends = "strict"
restrict_network = false

# Tool directories (read + exec). Absolute paths required (Seatbelt does not expand ~).
read_only = [
{ro}
]

read_write = [
  "./.devcage-data",
]

deny = [
  ".env",
  "local.env",
  ".env.local",
  "**/.env",
  "**/.env.*",
  "**/local.env",
  "**/*.pem",
  "**/*.p12",
  "**/*.key",
  "**/*id_rsa*",
  "**/*id_ed25519*",
  "**/credentials.json",
  "**/service-account*.json",
  "**/secrets.yaml",
  "**/secrets.yml",
  "**/secrets.toml",
  "**/.ssh",
  "**/.ssh/**",
  "**/.aws",
  "**/.aws/**",
  "**/.gnupg",
  "**/.gnupg/**",
  "**/.kube",
  "**/.kube/**",
  "**/.docker/config.json",
  "**/.config/gcloud/**",
  "**/.netrc",
  "**/.npmrc",
  "**/.pypirc",
  "**/Library/Keychains/**",
  "**/Library/Keychains",
]
"#
    )
}

/// Push `path` if it is missing (ok) or is an existing directory — never a file.
fn push_dir_if_present(out: &mut Vec<String>, path: &Path) {
    if path.exists() && !path.is_dir() {
        // Grok error: "Expected a directory but got a file"
        return;
    }
    out.push(path.display().to_string());
}

fn escape_toml_string(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Launch Grok in the combined sandbox + DevCage-ready mode.
///
/// # Errors
///
/// Returns an error when the workspace cannot be resolved, recipes fail to seed,
/// or the Grok binary cannot be started.
pub fn run_grok_mode(cfg: &Config, params: GrokModeParams) -> anyhow::Result<ExitCode> {
    let workspace = resolve_workspace(params.workspace)?;
    if !params.no_init {
        let written = init_grok_recipes(&workspace, params.force_init)?;
        if !written.is_empty() {
            eprintln!("devcage: seeded Grok recipes ({})", written.join(", "));
        }
    }
    warn_if_custom_recipe_blocks_docker(&workspace);

    let grok_bin = resolve_grok_bin(cfg);
    let (data_dir, data_note) = data_dir_for_grok_sandbox_child();
    let data_dir_str = data_dir.display().to_string();
    let deny_host = if params.allow_host_profile { "0" } else { "1" };

    let mut argv = vec![
        grok_bin.clone(),
        "--sandbox".to_owned(),
        params.sandbox.clone(),
    ];
    argv.extend(params.args.iter().cloned());

    if params.print_only {
        print_plan(
            &workspace,
            &data_dir_str,
            deny_host,
            &argv,
            data_note.as_deref().or(cfg.data_dir_note.as_deref()),
        );
        return Ok(ExitCode::SUCCESS);
    }

    if Path::new(&grok_bin) == Path::new("grok") && !which("grok") {
        anyhow::bail!("grok not found on PATH; install Grok Build or set DEVCAGE_DEFAULT_AGENT");
    }

    eprintln!("devcage mode: grok-sandbox");
    eprintln!("  sandbox:   {}", params.sandbox);
    eprintln!("  workspace: {}", workspace.display());
    eprintln!("  data_dir:  {data_dir_str}");
    eprintln!("  deny_host: {deny_host} (profile `host` blocked unless --allow-host-profile)");
    eprintln!("  scrub:     SSH_AUTH_SOCK, AWS_* secrets, GH/OpenAI/Anthropic tokens");
    if let Some(note) = data_note.as_ref().or(cfg.data_dir_note.as_ref()) {
        eprintln!("  note:      {note}");
    }
    eprintln!("  deep cage: devcage run -p offline|untrusted|agent -- <cmd>");
    eprintln!("  limits:    devcage limits");
    eprintln!();

    let mut cmd = Command::new(&grok_bin);
    cmd.arg("--sandbox").arg(&params.sandbox);
    cmd.args(&params.args);
    cmd.current_dir(&workspace);
    cmd.env("DEVCAGE_DATA_DIR", &data_dir_str);
    cmd.env("DEVCAGE_MODE", "grok-sandbox");
    cmd.env("DEVCAGE_GROK_SANDBOX", &params.sandbox);
    cmd.env("DEVCAGE_DENY_HOST", deny_host);
    // Stable PATH: system first, then this binary's dir, then existing PATH.
    cmd.env("PATH", child_path_env());
    for key in SCRUB_ENV {
        cmd.env_remove(*key);
    }
    cmd.stdin(Stdio::inherit());
    cmd.stdout(Stdio::inherit());
    cmd.stderr(Stdio::inherit());

    let status = cmd
        .status()
        .map_err(|e| anyhow::anyhow!("failed to start `{grok_bin}`: {e}"))?;
    let code = status.code().unwrap_or(1);
    Ok(exit_code_from_i32(code))
}

fn child_path_env() -> String {
    let mut parts: Vec<String> = vec![
        "/usr/bin".into(),
        "/bin".into(),
        "/usr/sbin".into(),
        "/sbin".into(),
        "/opt/homebrew/bin".into(),
        "/usr/local/bin".into(),
    ];
    if let Ok(exe) = std::env::current_exe() {
        if let Some(dir) = exe.parent() {
            parts.push(dir.display().to_string());
        }
    }
    if let Some(home) = std::env::var_os("HOME") {
        let h = PathBuf::from(home);
        parts.push(h.join(".local/bin").display().to_string());
        parts.push(h.join(".grok/bin").display().to_string());
    }
    if let Ok(existing) = std::env::var("PATH") {
        for p in existing.split(':') {
            if !p.is_empty() && !parts.iter().any(|x| x == p) {
                parts.push(p.to_owned());
            }
        }
    }
    parts.join(":")
}

fn resolve_grok_bin(cfg: &Config) -> String {
    let name = cfg.default_agent.as_str();
    if name == "grok" || name.ends_with("/grok") {
        name.to_owned()
    } else {
        "grok".to_owned()
    }
}

fn print_plan(
    workspace: &Path,
    data_dir: &str,
    deny_host: &str,
    argv: &[String],
    note: Option<&str>,
) {
    println!("mode: grok-sandbox");
    println!("workspace: {}", workspace.display());
    println!("DEVCAGE_DATA_DIR={data_dir}");
    println!("DEVCAGE_MODE=grok-sandbox");
    println!("DEVCAGE_DENY_HOST={deny_host}");
    println!("scrub_env: {}", SCRUB_ENV.join(","));
    if let Some(n) = note {
        println!("data_dir_note: {n}");
    }
    println!("command: {}", argv.join(" "));
}

fn exit_code_from_i32(code: i32) -> ExitCode {
    if code == 0 {
        ExitCode::SUCCESS
    } else if (1..=255).contains(&code) {
        ExitCode::from(u8::try_from(code).unwrap_or(1))
    } else {
        ExitCode::FAILURE
    }
}

#[cfg(test)]
mod tests {
    use super::{init_grok_recipes, render_sandbox_toml, EMBEDDED_CONFIG_TOML};
    use std::fs;

    #[test]
    fn embedded_recipes_nonempty() {
        let sb = render_sandbox_toml();
        assert!(sb.contains("keys-first"));
        assert!(sb.contains("extends = \"strict\""));
        assert!(sb.contains("must be directories"));
        assert!(sb.contains("restrict_network = false"));
        assert!(!sb.contains("restrict_network = true"));
        assert!(sb.contains("\n  \".env\","));
        assert!(sb.contains("\n  \"local.env\","));
        assert!(!sb.contains(".gitconfig"));
        assert!(EMBEDDED_CONFIG_TOML.contains("devcage run -p host"));
        assert!(EMBEDDED_CONFIG_TOML.contains("[permission]"));
    }

    #[test]
    fn push_dir_skips_files() {
        let f = std::env::temp_dir().join(format!(
            "devcage-not-dir-{}-{}",
            std::process::id(),
            unique_nanos()
        ));
        fs::write(&f, b"x").expect("write");
        let mut v = Vec::new();
        super::push_dir_if_present(&mut v, &f);
        assert!(v.is_empty());
        let _ = fs::remove_file(f);
    }

    #[test]
    fn init_writes_once() {
        let dir = std::env::temp_dir().join(format!(
            "devcage-grok-init-{}-{}",
            std::process::id(),
            unique_nanos()
        ));
        fs::create_dir_all(&dir).expect("mkdir");
        let w1 = init_grok_recipes(&dir, false).expect("init");
        assert_eq!(w1.len(), 2);
        let w2 = init_grok_recipes(&dir, false).expect("init again");
        assert!(w2.is_empty());
        let w3 = init_grok_recipes(&dir, true).expect("force");
        assert_eq!(w3.len(), 2);
        assert!(dir.join(".grok/sandbox.toml").is_file());
        assert!(dir.join(".grok/config.toml").is_file());
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn init_refreshes_stale_generated_sandbox() {
        let dir = std::env::temp_dir().join(format!(
            "devcage-grok-stale-{}-{}",
            std::process::id(),
            unique_nanos()
        ));
        fs::create_dir_all(&dir).expect("mkdir");
        init_grok_recipes(&dir, false).expect("init");
        let path = dir.join(".grok/sandbox.toml");
        let stale = fs::read_to_string(&path)
            .expect("read")
            .replace("restrict_network = false", "restrict_network = true");
        fs::write(&path, stale).expect("write stale");
        let written = init_grok_recipes(&dir, false).expect("refresh");
        assert_eq!(written, vec![".grok/sandbox.toml".to_owned()]);
        let updated = fs::read_to_string(&path).expect("read updated");
        assert!(updated.contains("restrict_network = false"));
        assert!(!updated.contains("restrict_network = true"));
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn init_leaves_custom_sandbox_alone() {
        let dir = std::env::temp_dir().join(format!(
            "devcage-grok-custom-{}-{}",
            std::process::id(),
            unique_nanos()
        ));
        let grok_dir = dir.join(".grok");
        fs::create_dir_all(&grok_dir).expect("mkdir");
        let sandbox = grok_dir.join("sandbox.toml");
        fs::write(
            &sandbox,
            "[profiles.keys-first]\nextends = \"strict\"\nrestrict_network = true\n",
        )
        .expect("write custom");
        let written = init_grok_recipes(&dir, false).expect("init");
        assert_eq!(written, vec![".grok/config.toml".to_owned()]);
        let body = fs::read_to_string(&sandbox).expect("read custom");
        assert!(body.contains("restrict_network = true"));
        assert!(!body.contains("Generated by devcage init-grok"));
        let _ = fs::remove_dir_all(dir);
    }

    #[test]
    fn generated_recipe_without_exact_env_is_stale() {
        let body = "# Generated by devcage init-grok / devcage grok\nrestrict_network = false\ndeny = [\n  \"**/.env\",\n]\n";
        assert!(super::generated_sandbox_recipe_stale(body));
        assert!(!super::generated_sandbox_recipe_stale(
            "# hand written\nrestrict_network = true\n"
        ));
    }

    fn unique_nanos() -> u128 {
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0)
    }
}
